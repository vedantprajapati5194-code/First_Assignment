## 5. Looping (For, While)


''' Q:1)  Practical Example 1: Write a Python program to print each fruit in a list using a simple for
loop. List1 = ['apple', 'banana', 'mango']'''


# Create a list of fruits

list1 = ['apple', 'banana', 'mango']

# Print each fruit

for fruit in list1:
    print(fruit)
    